    plt.ylabel('Actual')
    plt.xlabel('Predicted')
    plt.savefig(f'outputs/plots/{name.lower().replace(" ", "_")}_cm.png')
    plt.close()

    # Print Report
    print(f"\n=== {name} Classification Report ===")
    print(classification_report(y_true, y_pred, target_names=['Cats', 'Dogs']))

