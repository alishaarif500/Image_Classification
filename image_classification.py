"""### Dataset Filtering & Splitting
Now, we split the raw images into clean train, validation, and test sets. We will filter out corrupted images (e.g., zero-byte files) to ensure stable model training.
"""

import os
import shutil
import random

def clean_and_split_data(src_dir, train_dir, val_dir, test_dir, split_ratio=(0.8, 0.1, 0.1)):
    all_files = []
    for root, _, files in os.walk(src_dir):
        for file in files:
            if file.lower().endswith(('.jpg', '.jpeg')):
                path = os.path.join(root, file)
                # Filter out empty or corrupted images
                if os.path.getsize(path) > 1024:
                    all_files.append(path)

    # Group by class
    cats = [f for f in all_files if 'cat' in os.path.basename(f).lower() or 'cat' in f.lower()]
    dogs = [f for f in all_files if 'dog' in os.path.basename(f).lower() or 'dog' in f.lower()]

    random.seed(42)
    random.shuffle(cats)
    random.shuffle(dogs)

    # Limit to 1000 images per class for execution speed in this environment
    cats = cats[:1000]
    dogs = dogs[:1000]

    train_idx = int(len(cats) * split_ratio[0])
    val_idx = train_idx + int(len(cats) * split_ratio[1])

    splits = {
        'train/cats': cats[:train_idx],
        'train/dogs': dogs[:train_idx],
        'val/cats': cats[train_idx:val_idx],
        'val/dogs': dogs[train_idx:val_idx],
        'test/cats': cats[val_idx:],
        'test/dogs': dogs[val_idx:]
    }

    for split_name, files in splits.items():
        dest_path = f"data/processed/{split_name}"
        os.makedirs(dest_path, exist_ok=True)
        for f in files:
            shutil.copy(f, os.path.join(dest_path, os.path.basename(f)))

clean_and_split_data('data/raw/PetImages', 'data/processed/train', 'data/processed/val', 'data/processed/test')
